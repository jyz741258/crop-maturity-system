def get_knowledge(crop_type: str, knowledge_type: str = None) -> Dict[str, Any]:
    """
    获取作物知识库信息
    
    Args:
        crop_type: 作物类型
        knowledge_type: 知识类型（可选）：planting_method, environment, pesticide, diseases, varieties, harvest
    
    Returns:
        知识库信息字典
    """
    crop_data = CROP_KNOWLEDGE.get(crop_type)
    if not crop_data:
        return {}
    
    if knowledge_type and knowledge_type in crop_data:
        return {knowledge_type: crop_data[knowledge_type]}
    
    return crop_data

def search_knowledge(query: str) -> Dict[str, Any]:
    """
    根据查询词搜索知识库
    
    Args:
        query: 查询词
        
    Returns:
        匹配的知识库信息
    """
    results = {}
    query_lower = query.lower()
    
    for crop_type, crop_data in CROP_KNOWLEDGE.items():
        crop_name = crop_data['name']
        crop_name_lower = crop_name.lower()
        crop_type_lower = crop_type.lower()
        
        if crop_name_lower in query_lower or crop_type_lower in query_lower:
            if '种植' in query_lower:
                results[crop_name] = {'种植方式': crop_data.get('planting_method', '')}
            elif '环境' in query_lower or '气候' in query_lower:
                results[crop_name] = {'环境需求': crop_data.get('environment', '')}
            elif '农药' in query_lower or '病虫害' in query_lower:
                results[crop_name] = {
                    '农药使用': crop_data.get('pesticide', ''),
                    '病虫害防治': crop_data.get('diseases', {})
                }
            elif '品种' in query_lower:
                results[crop_name] = {'品种介绍': crop_data.get('varieties', {})}
            elif '采收' in query_lower:
                results[crop_name] = {'采收技术': crop_data.get('harvest', '')}
            else:
                results[crop_name] = crop_data
    
    return results

def get_all_crop_names() -> list:
    """获取所有作物名称"""
    return [data['name'] for data in CROP_KNOWLEDGE.values()]
